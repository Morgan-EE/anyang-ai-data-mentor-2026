/* QR 행 데이터(16진수)를 SVG로 변환 */
(function () {
  var S = window.MD.survey, n = S.qrSize, d = "";
  S.qrRows.forEach(function (hex, y) {
    var bits = hex.split("").map(function (c) { return ("000" + parseInt(c, 16).toString(2)).slice(-4); }).join("");
    for (var x = 0; x < n; x++) if (bits[x] === "1") d += "M" + x + "," + y + "h1v1h-1z";
  });
  S.qrSvg = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ' + n + " " + n + '" shape-rendering="crispEdges"><rect width="' + n + '" height="' + n + '" fill="#fff"/><path d="' + d + '" fill="#000"/></svg>';
})();

